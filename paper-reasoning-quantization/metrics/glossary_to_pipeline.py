#!/usr/bin/env python3
"""Convert arrow-format domain glossaries into the pipeline glossary format.

The translation pipeline (council/tools/local_translate.py:load_glossary) and
metrics/defects.py:parse_glossary both parse ONLY the bold form

    **EN term** (RU equivalent)

while per-domain pair files (corpus/freebsd-ru/gloss_pairs/F*.txt) use the
judge format `EN term -> RU equivalent` (PLAN.md §6.2). Without conversion the
domain glossary loads as empty: glossary hints and force-apply silently stop
working and D5/D7 report zero terms.

Pair sources are merged with explicit precedence: per-document pair files win
over the domain summary glossary, because per-document pairs are extracted from
the actual reference translation of that document.

Pairs that carry no information for a translation glossary are dropped and
reported:
  * identity pairs (EN == RU): force-apply is a no-op and D7 would count the
    untranslated term as a contamination trap (`ZFS -> ZFS`);
  * pairs whose RU side is empty after stripping parenthetical glosses.

Usage:
  glossary_to_pipeline.py                                  # freebsd-ru domain
  glossary_to_pipeline.py --pairs-dir corpus/freebsd-ru/gloss_pairs \
                          --summary corpus/freebsd-ru/glossary.md \
                          --out corpus/freebsd-ru/glossary_pipeline.md
"""
import argparse, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ARROW = re.compile(r"^\s*(?P<en>[^>#][^>]*?)\s*->\s*(?P<ru>.+?)\s*$")

def parse_arrow(text):
    """Yield (en, ru) from `EN -> RU` lines, skipping comments and blanks."""
    for line in text.splitlines():
        if line.lstrip().startswith("#") or "->" not in line:
            continue
        m = ARROW.match(line)
        if m:
            yield m.group("en").strip(), m.group("ru").strip()

def normalize_ru(ru):
    """Take the required equivalent, dropping parenthetical glosses.

    `DNS (система доменных имён)` -> `DNS`: the bold-form parser stops at the
    first ')' and would otherwise store a truncated equivalent.
    """
    return ru.split("(", 1)[0].strip().rstrip(".,;:").strip()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs-dir", default=str(ROOT / "corpus/freebsd-ru/gloss_pairs"))
    ap.add_argument("--summary", default=str(ROOT / "corpus/freebsd-ru/glossary.md"))
    ap.add_argument("--out", default=str(ROOT / "corpus/freebsd-ru/glossary_pipeline.md"))
    a = ap.parse_args()

    pairs, dropped, conflicts = {}, [], []

    def offer(en, ru, origin):
        ru = normalize_ru(ru)
        key = en.lower()
        if not en or not ru:
            dropped.append((en, ru, origin, "empty RU"))
            return
        if ru.lower() == key:
            dropped.append((en, ru, origin, "identity (EN == RU)"))
            return
        if key in pairs and pairs[key][1] != ru:
            conflicts.append((pairs[key][0], pairs[key][1], pairs[key][2], en, ru, origin))
        if key in pairs and origin != "pairs":
            return  # per-document pair files already won
        pairs[key] = (en, ru, origin)

    for pf in sorted(Path(a.pairs_dir).glob("*.txt")):
        for en, ru in parse_arrow(pf.read_text(encoding="utf-8")):
            offer(en, ru, pf.name)
    summary = Path(a.summary)
    if summary.exists():
        for en, ru in parse_arrow(summary.read_text(encoding="utf-8")):
            offer(en, ru, summary.name)

    lines = [
        "# FreeBSD Handbook EN->RU glossary, pipeline format (**EN** (RU)).",
        "# Generated by metrics/glossary_to_pipeline.py from corpus/freebsd-ru/gloss_pairs/*",
        "# and glossary.md. Do not edit by hand - edit the pair files and regenerate.",
        "# Required by local_translate.py:load_glossary and defects.py:parse_glossary.",
        "",
    ]
    for key in sorted(pairs):
        en, ru, _ = pairs[key]
        lines.append(f"**{en}** ({ru})")
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"wrote {out} ({len(pairs)} pairs)")
    if conflicts:
        print(f"conflicts resolved in favour of pair files: {len(conflicts)}")
        for en, kept, kept_from, _en2, overridden, over_from in conflicts:
            print(f"  {en}: kept '{kept}' ({kept_from}) over '{overridden}' ({over_from})")
    if dropped:
        print(f"dropped: {len(dropped)}")
        for en, ru, origin, why in dropped:
            print(f"  {en} -> {ru} [{origin}]: {why}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
